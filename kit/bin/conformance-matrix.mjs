import { readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const CLAUSES = ["C1", "C2", "C3", "C4", "C5", "C6", "C7"];

export function validateFixtureProvenance(fixtures) {
  for (const fixture of fixtures) {
    if (!fixture.files.includes("PROVENANCE.md")) {
      throw new Error(`${fixture.path} is missing PROVENANCE.md`);
    }
  }
  return true;
}

function discrepancyFor(discrepancies, backend, clause) {
  return discrepancies.find((entry) => entry.backend === backend && entry.clause === clause &&
    ["ACCEPTED", "INVESTIGATING", "WILL-FIX"].includes(entry.status));
}

export function generateCoverageMatrix({ contracts, adapters, clauseResults, conditionResults, discrepancies }) {
  const errors = [];
  const clauseRows = ["| Family | Backend | C1 | C2 | C3 | C4 | C5 | C6 | C7 |", "|---|---|---|---|---|---|---|---|---|"];
  for (const contract of contracts) {
    for (const adapter of adapters) {
      const cells = CLAUSES.map((clause) => {
        const result = clauseResults.find((entry) => entry.family === contract.family && entry.backend === adapter.id && entry.clause === clause);
        if (!result) {
          if ((contract.shipped_backends ?? []).includes(adapter.id)) errors.push(`${contract.family}/${adapter.id}/${clause} is untested`);
          return "";
        }
        if (result.status === "PASS") return "PASS";
        if (result.status === "XFAIL" && discrepancyFor(discrepancies, adapter.id, clause)) return `XFAIL:${discrepancyFor(discrepancies, adapter.id, clause).id}`;
        errors.push(`${contract.family}/${adapter.id}/${clause} has unrecognized status ${result.status}`);
        return result.status;
      });
      clauseRows.push(`| ${contract.family} | ${adapter.id} | ${cells.join(" | ")} |`);
    }
  }
  const conditionRows = ["| Family | Condition | Status |", "|---|---|---|"];
  for (const contract of contracts) {
    const rows = conditionResults.filter((entry) => entry.family === contract.family);
    for (const entry of rows) conditionRows.push(`| ${contract.family} | ${entry.condition} | ${entry.status} |`);
  }
  const markdown = [
    "# Classifier conformance coverage",
    "",
    "Generated by `node kit/bin/conformance-matrix.mjs`; do not edit by hand.",
    "",
    "C1–C7 run offline over recorded answers with injected transports. Blank cells mean untested; XFAIL cells require a current discrepancy entry.",
    "",
    "## Family × backend × clause",
    "",
    ...clauseRows,
    "",
    "## Family × condition",
    "",
    ...conditionRows,
    "",
  ].join("\n");
  return { ok: errors.length === 0, errors, markdown };
}

export async function fixtureInventory(root) {
  const entries = await readdir(root, { withFileTypes: true });
  return entries.filter((entry) => entry.isDirectory()).map((entry) => ({
    path: `kit/fixtures/${entry.name}`,
    files: [],
  }));
}

export async function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const repo = resolve(here, "../..");
  const { runConformanceSuite } = await import("../conformance/runner.mjs");
  const suite = await runConformanceSuite();
  const matrix = generateCoverageMatrix(suite);
  const inventory = await fixtureInventory(resolve(repo, "kit/fixtures"));
  for (const fixture of inventory) {
    const files = await readdir(resolve(repo, fixture.path));
    fixture.files = files;
  }
  validateFixtureProvenance(inventory);
  await writeFile(resolve(repo, "work/plan-20261004/CONFORMANCE.md"), matrix.markdown);
  if (!matrix.ok) throw new Error(matrix.errors.join("\n"));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
